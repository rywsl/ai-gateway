-- 0001_initial.sql — gw-store v1 schema (§8.2).
--
-- Every entity table shares three control columns:
--   version    BIGINT       monotonic version, written by upsert path.
--   updated_at TIMESTAMPTZ  last-write timestamp.
--   deleted_at TIMESTAMPTZ  soft-delete tombstone (NULL means alive).
--
-- Hot fields are stored in a single JSONB `payload` column for v1; structured
-- indexes / generated columns can be added in a follow-up migration once the
-- access patterns stabilise.

CREATE TABLE IF NOT EXISTS users (
    id          TEXT        PRIMARY KEY,
    payload     JSONB       NOT NULL,
    version     BIGINT      NOT NULL DEFAULT 0,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at  TIMESTAMPTZ NULL
);

CREATE TABLE IF NOT EXISTS user_groups (
    id          TEXT        PRIMARY KEY,
